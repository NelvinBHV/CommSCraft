#!/usr/bin/env python3
"""Collect conflicts (K), gaps (L) and open points (O) from docs/protocol/evidence/*.md.

Writes docs/protocol/conflicts-gaps-open-points.md. Only bullet lines that start with an
ID (`- K-…`, `- **L-…`, `- O-…`) before the first "## Later finding" heading are taken;
files 38 and 39 are summaries of the follow-up research and are skipped. The current
status of every gap and open point is kept in STATUS below and must be updated together
with the evidence files.
"""
