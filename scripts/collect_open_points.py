ID_RE = re.compile(r"^- (?:\*\*)?([KLO])-([A-Z0-9]+(?:-[0-9]+)?)")


def collect():
    rows = {"K": [], "L": [], "O": []}
    for path in sorted(EVIDENCE.glob("*.md")):
        if path.name.startswith(("38-", "39-")):
            continue
        text = path.read_text(encoding="utf-8").split("\n## Later finding")[0]
        for line in text.splitlines():
            m = ID_RE.match(line)
            if not m:
                continue
            kind = m.group(1)
            ident = f"{kind}-{m.group(2)}"
            entry = line[2:].strip().replace("|", "\\|")
            rows[kind].append((path.name, ident, entry))
    return rows


def main():
    rows = collect()
    missing = [i for k in "LO" for (_, i, _) in rows[k] if i not in STATUS]
    if missing:
        sys.exit(f"status missing for: {', '.join(missing)}")
    out = [
        "# Conflicts, gaps and open points",
        "",
        "Generated by `scripts/collect_open_points.py` from [`evidence/`](evidence/) – do not edit by hand.",
        "",
        "- **K** = documented contradiction between passages (with the decision which passage is authoritative),",
        "- **L** = gap: a needed specification was missing from the Microsoft package,",
        "- **O** = open: not fixed by the sources when found; the status says how it was closed or which interop test case ([`../interop-tests.md`](../interop-tests.md)) decides it.",
        "- The status column reflects the research of files 38 (IETF/archive) and 39 (official documentation, archives, open-source implementations, fourth normative pass OB-39 … OB-51); \"secondary evidence\" is not normative and still needs interop confirmation.",
        "",
    ]
    titles = {"K": "Conflicts (K)", "L": "Gaps (L)", "O": "Open points (O)"}
    for kind in "KLO":
        out.append(f"## {titles[kind]} – {len(rows[kind])} entries")
        out.append("")
        if kind == "K":
            out += ["| Source | Entry |", "|---|---|"]
            out += [f"| evidence/{f} | {e} |" for (f, _, e) in rows[kind]]
        else:
            out += ["| Source | Entry | Status |", "|---|---|---|"]
            out += [f"| evidence/{f} | {e} | {STATUS[i]} |" for (f, i, e) in rows[kind]]
        out.append("")
    OUT.write_text("\n".join(out), encoding="utf-8")
    print({k: len(v) for k, v in rows.items()})


if __name__ == "__main__":
    main()
